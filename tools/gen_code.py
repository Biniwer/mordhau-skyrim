"""Generate plugin/src/gen/Sheets.h from the JSON sheets: one struct instance per row. Run before every build."""
import json, os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
T = '\t'


def rows(name):
    return json.load(open(os.path.join(root, 'sheets', name + '.json'), encoding='utf-8'))['rows']


def s(v):
    return json.dumps(v or '')  # JSON string escaping is valid C++ for these names


def b(v):
    return 'true' if v else 'false'


def fl(v):
    return f'{float(v)}f' if v is not None else '-1.0f'


out = ['// GENERATED by tools/gen_code.py from sheets/*.json. Do not edit; change the sheet and regenerate.', '#pragma once', '',
       'namespace dm::sheets', '{',
       T + 'enum class Layer { kUpper, kLower, kAttach };', '',
       T + 'struct Bone { const char* id; const char* skyrimNode; const char* dirSkyrimNode; Layer layer; bool firstPerson; const char* mordhauBone; const char* dirMordhauBone; };',
       T + 'inline constexpr Bone kBones[] = {']
for r in rows('bone_map'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["skyrim_node"])}, {s(r["dir_skyrim_node"])}, Layer::k{r["layer"].capitalize()}, {b(r["first_person"])}, {s(r["mordhau_bone"])}, {s(r["dir_mordhau_bone"])} }},')

out += [T + '};', '',
        T + '// angle: mouse-movement direction in degrees, 0 = right, 90 = up; [from, to). hasAngle false = not chosen by flick.',
        T + "// move: MORDHAU's attack move; kClips maps a weapon's clip set + move to the clip.",
        T + 'struct Swing { const char* id; bool stab; bool hasAngle; float angleFrom; float angleTo; const char* move; const char* skyrimFallback; const char* request; };',
        T + 'inline constexpr Swing kSwings[] = {']
for r in rows('swings'):
    a = r['angle_deg']
    out.append(f'{T}{T}{{ {s(r["id"])}, {b(r["kind"] == "stab")}, {b(a is not None)}, {float(a[0]) if a else 0.0}f, {float(a[1]) if a else 0.0}f, '
               f'{s(r["move"])}, {s(r["skyrim_fallback"])}, {s(r["mordhau_request"])} }},')

out += [T + '};', '',
        T + '// weaponType: RE::WEAPON_TYPE value name; keyword: extra Skyrim keyword the weapon must have ("" = none).',
        T + 'struct WeaponFamily { const char* id; const char* weaponType; const char* keyword; const char* mordhauWeapon; const char* clipSet; };',
        T + 'inline constexpr WeaponFamily kWeaponFamilies[] = {']
for r in rows('weapon_families'):
    t, _, kw = r['skyrim_weapon_type'].partition('+')
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(t)}, {s(kw)}, {s(r["mordhau_weapon"])}, {s(r["clip_set"])} }},')

out += [T + '};', '',
        T + '// clip3p / clip1p: paths under Mordhau/Content/Mordhau/Animations/RawClips ("" = not looked up yet).',
        T + '// windupEnd / releaseEnd: fractions of the clip where wind-up and release end (negative = not measured yet).',
        T + '// riposte3p: played instead of clip3p for a riposte, with its own fractions ("" / negative = none).',
        T + 'struct ClipRow { const char* clipSet; const char* move; const char* clip3p; const char* clip1p; float windupEnd; float releaseEnd; const char* riposte3p; float riposteWindupEnd; float riposteReleaseEnd; };',
        T + 'inline constexpr ClipRow kClips[] = {']
for r in rows('clips'):
    out.append(f'{T}{T}{{ {s(r["clip_set"])}, {s(r["move"])}, {s(r["clip_3p"])}, {s(r["clip_1p"])}, {fl(r["windup_end"])}, {fl(r["release_end"])}, '
               f'{s(r["riposte_3p"])}, {fl(r["riposte_windup_end"])}, {fl(r["riposte_release_end"])} }},')

out += [T + '};', '',
        T + "// property: name inside a MORDHAU weapon's StrikeAttack / StabAttack block. fallback: this mod's own value when",
        T + "// the player's MORDHAU has no value for it (negative = none chosen).",
        T + 'struct AttackStat { const char* id; const char* property; float fallback; };',
        T + 'inline constexpr AttackStat kAttackStats[] = {']
for r in rows('attack_stats'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["mordhau_property"])}, {fl(r["fallback"])} }},')

out += [T + '};', '',
        T + '// Helper bones along a limb. followChild: take a share of the roll of `relativeTo` (the hand) relative to the owner;',
        T + "// otherwise undo a share of the owner's roll relative to `relativeTo` (the shoulder side).",
        T + 'struct TwistBone { const char* id; const char* skyrimNode; const char* ownerNode; const char* towardNode; const char* relativeToNode; bool followChild; };',
        T + 'inline constexpr TwistBone kTwistBones[] = {']
node_of = {r['id']: r['skyrim_node'] for r in rows('bone_map')}
for r in rows('twist_bones'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["skyrim_node"])}, {s(node_of[r["owner"]])}, {s(node_of[r["toward"]])}, {s(node_of[r["relative_to"]])}, {b(r["mode"] == "follow_child")} }},')

out += [T + '};', '',
        T + "// property: name on MORDHAU's parry motion definition (\"\" = MORDHAU's data has no such number). fallback: this mod's own value.",
        T + 'struct ParryStat { const char* id; const char* property; float fallback; };',
        T + 'inline constexpr ParryStat kParryStats[] = {']
for r in rows('parry_stats'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["mordhau_property"])}, {fl(r["fallback"])} }},')

out += [T + '};', '',
        T + "// property: name on MORDHAU's character movement component or character (\"\" = not in MORDHAU's data). fallback: negative = none.",
        T + 'struct MoveStat { const char* id; const char* property; float fallback; };',
        T + 'inline constexpr MoveStat kMoveStats[] = {']
for r in rows('movement'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["mordhau_property"])}, {fl(r["fallback"])} }},')

out += [T + '};', '',
        T + '// Side-by-side mode: extra Skyrim buttons -> MORDHAU inputs (device: 0 keyboard, 1 mouse; code: Skyrim button id).',
        T + 'struct LiveInput { const char* id; int device; int code; const char* request; };',
        T + 'inline constexpr LiveInput kLiveInputs[] = {']
for r in rows('live_input'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {int(r["device"])}, {int(r["code"])}, {s(r["request"])} }},')

out += [T + '};', '',
        T + "// MORDHAU's own voice / emote menu: where it is in MORDHAU's window (sheets/menus.json, row window_part).",
        T + 'struct MenuPart { float left, right, top, bottom; };',
        T + 'inline constexpr MenuPart kMenuPart[] = {']
for r in rows('menus'):
    if r['id'] == 'window_part':
        out.append(f'{T}{T}{{ {float(r["left"])}f, {float(r["right"])}f, {float(r["top"])}f, {float(r["bottom"])}f }},')

out += [T + '};', '',
        T + "// Skyrim weapon -> MORDHAU weapon by family and words in the name (sheets/weapon_map.json); first match wins.",
        T + 'struct WeaponMapRow { const char* family; const char* contains; const char* mordhauWeapon; };',
        T + 'inline constexpr WeaponMapRow kWeaponMap[] = {']
for r in rows('weapon_map'):
    out.append(f'{T}{T}{{ {s(r["family"])}, {s(r["name_contains"])}, {s(r["mordhau_weapon"])} }},')

out += [T + '};', '',
        T + "// Skyrim shield -> MORDHAU shield by words in its name (sheets/shield_map.json); first match wins.",
        T + 'struct ShieldMapRow { const char* contains; const char* armour; const char* mordhauShield; };',
        T + 'inline constexpr ShieldMapRow kShieldMap[] = {']
for r in rows('shield_map'):
    out.append(f'{T}{T}{{ {s(r["name_contains"])}, {s(r["armour"])}, {s(r["mordhau_shield"])} }},')
out += [T + '};', '',
        T + "// Skyrim creatures that fight with a MORDHAU Demon Horde creature's moves (sheets/creature_fighters.json); first match wins.",
        T + 'struct CreatureFighterRow { const char* raceContains; const char* demon; float headCm; const char* banned; const char* weapon; const char* skyrimBones; };',
        T + 'inline constexpr CreatureFighterRow kCreatureFighters[] = {']
for r in rows('creature_fighters'):
    out.append(f'{T}{T}{{ {s(r["race_contains"])}, {s(r["demon"])}, {float(r["head_cm"])}f, {s(r["banned"])}, {s(r.get("weapon", ""))}, {s(r.get("skyrim_bones", ""))} }},')
out += [T + '};', '',
        T + "// Demon Horde's weapon blessings on enchanted weapons (sheets/blessings.json); first row whose resist matches wins.",
        T + 'struct BlessingRow { const char* id; const char* resist; float glow[3]; float spark[3]; float smoke[3]; float trail[3]; };',
        T + 'inline constexpr BlessingRow kBlessings[] = {']
bless = json.load(open(os.path.join(root, 'sheets', 'blessings.json'), encoding='utf-8'))
for r in bless['rows']:
    cols = ', '.join('{ ' + ', '.join(f'{float(x)}f' for x in r[k]) + ' }' for k in ('glow', 'spark', 'smoke', 'trail'))
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["resist"])}, {cols} }},')
out += [T + '};',
        T + 'struct BlessingTexture { const char* id; const char* path; };',
        T + 'inline constexpr BlessingTexture kBlessingTextures[] = {']
for r in bless['textures']:
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["path"])} }},')
out += [T + '};', '',
        T + "// Blunt MORDHAU weapons whose killing head hit takes the head off (sheets/gore.json); names separated by |.",
        T + 'inline constexpr const char* kGoreBlunt = ' + s(next(r for r in rows('gore') if r['id'] == 'head_explodes')['weapons']) + ';',
        T + 'inline constexpr int kGoreDummy[] = {', T + T + '0,']
out += [T + '};', '',
        T + "// MORDHAU weapons as Skyrim items (sheets/mordhau_items.json), in sheet order (the order gives their ids).",
        T + 'struct MordhauItem { const char* name; const char* mordhauWeapon; const char* skyrimLike; float damage; float weight; int value; };',
        T + 'inline constexpr MordhauItem kMordhauItems[] = {']
for r in rows('mordhau_items'):
    out.append(f'{T}{T}{{ {s(r["name"])}, {s(r["mordhau_weapon"])}, {s(r["skyrim_like"])}, {float(r["damage"])}f, {float(r["weight"])}f, {int(r["value"])} }},')

out += [T + '};', '',
        T + "// MORDHAU's camera (sheets/camera.json): centimetres and degrees.",
        T + 'struct CameraValue { const char* id; float value; };',
        T + 'inline constexpr CameraValue kCamera[] = {']
for r in rows('camera'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {float(r["value"])}f }},')

out += [T + '};', '',
        T + "// How MORDHAU-judged hits follow Skyrim's progression (sheets/progression.json).",
        T + 'inline constexpr CameraValue kProgression[] = {']
for r in rows('progression'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {float(r["value"])}f }},')

out += [T + '};', '',
        T + "// What MORDHAU's character sets down or throws, once in Skyrim's world (sheets/builds.json).",
        T + 'inline constexpr CameraValue kBuilds[] = {']
for r in rows('builds'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {float(r["value"])}f }},')

out += [T + '};', '',
        T + "// What the plugin's own baker builds from MORDHAU's files (sheets/looks.json, sheets/props.json,",
        T + "// sheets/standin_looks.json): the outfits and creatures by number, the props, the default mercenary.",
        T + 'struct Look { const char* id; const char* lookClass; const char* head; const char* coif; const char* upperChest; const char* lowerChest; const char* shoulders;',
        T + '	const char* arms; const char* hands; const char* legs; const char* feet; int colour1; int colour2; const char* model; const char* colourMap; const char* normalMap; };',
        T + 'inline constexpr Look kLooks[] = {']
for r in rows('looks'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["class"])}, {s(r.get("head"))}, {s(r.get("coif"))}, {s(r.get("upper_chest"))}, {s(r.get("lower_chest"))}, {s(r.get("shoulders"))}, '
               f'{s(r.get("arms"))}, {s(r.get("hands"))}, {s(r.get("legs"))}, {s(r.get("feet"))}, {int(r.get("colour_1") or 0)}, {int(r.get("colour_2") or 0)}, '
               f'{s(r.get("model"))}, {s(r.get("colour_map"))}, {s(r.get("normal_map"))} }},')
out += [T + '};', '',
        T + 'struct Prop { const char* id; const char* kind; const char* model; const char* colourMap; const char* normalMap; const char* surfaceMap; const char* weapon; };',
        T + 'inline constexpr Prop kProps[] = {']
for r in rows('props'):
    out.append(f'{T}{T}{{ {s(r["id"])}, {s(r["kind"])}, {s(r.get("model"))}, {s(r.get("colour_map"))}, {s(r.get("normal_map"))}, {s(r.get("surface_map"))}, {s(r.get("weapon_bp"))} }},')
out += [T + '};', '',
        T + "// the mercenary used when the player has not named one (a file player.txt in the cache folder) and has one of this name",
        T + f'inline constexpr const char* kDefaultMercenary = {s(json.load(open(os.path.join(root, "sheets", "standin_looks.json"), encoding="utf-8"))["player"])};']

fs = json.load(open(os.path.join(root, 'sheets', 'first_start.json'), encoding='utf-8'))
out += ['', T + "// The first-start message box (sheets/first_start.json): MORDHAU is not started before the player accepts it.",
        T + f'inline constexpr int kFirstStartVersion = {int(fs["version"])};',
        T + f'inline constexpr const char* kFirstStartBody = {json.dumps(fs["body"])};',
        T + f'inline constexpr const char* kFirstStartAccept = {json.dumps(fs["accept"])};',
        T + f'inline constexpr const char* kFirstStartDecline = {json.dumps(fs["decline"])};']
out += ['}', '']
dst = os.path.join(root, 'plugin', 'src', 'gen')
os.makedirs(dst, exist_ok=True)
open(os.path.join(dst, 'Sheets.h'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote plugin/src/gen/Sheets.h')
